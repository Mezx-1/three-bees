@router.get("/search")
def search(q: str = Query(..., min_length=2, max_length=200), db: Session = Depends(get_db), user: User = Depends(current_user)):
    """One search box for everything: checks (by title, id or type), evidence (phone, domain, link, email, file hash)
    and incidents. Matching is a simple case-insensitive 'contains'."""
    from sqlalchemy import String, cast, or_

    from ..deps import ser_incident
    from ..models import Incident, Indicator

    like = f"%{q.strip()}%"
    analyses = db.scalars(select(Analysis).where(or_(Analysis.title.ilike(like), Analysis.id.ilike(like),
                                                     Analysis.classification.ilike(like), cast(Analysis.report, String).ilike(like)))
                          .order_by(Analysis.created_at.desc()).limit(6)).all()
    evidence = []
    for ind in db.scalars(select(Indicator).where(Indicator.value.ilike(like), Indicator.analysis_id.is_not(None))
                          .order_by(Indicator.created_at.desc()).limit(30)).all():
        if len(evidence) >= 6:
            break
        if any(e["value"] == ind.value and e["analysis_id"] == ind.analysis_id for e in evidence):
            continue
        evidence.append({"type": ind.type, "value": ind.value, "analysis_id": ind.analysis_id, "malicious": ind.malicious})
    incidents = db.scalars(select(Incident).where(or_(Incident.title.ilike(like), Incident.id.ilike(like)))
                           .order_by(Incident.created_at.desc()).limit(5)).all()
    return {"query": q, "analyses": [ser_analysis(a) for a in analyses],
            "evidence": evidence,
            "incidents": [ser_incident(i) for i in incidents]}


